# === Парсинг даты ===

def parse_date(text):
    text = text.strip()
    for pat in [r"(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{4})", r"(\d{2})(\d{2})(\d{4})"]:
        m = re.match(pat, text)
        if m:
            d, mo, y = int(m.group(1)), int(m.group(2)), int(m.group(3))
            try:
                datetime(y, mo, d)
                return d, mo, y
            except ValueError:
                continue
    return None

